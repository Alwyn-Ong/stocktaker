import Constants from 'expo-constants';
import { Item, Location, UnknownBarcode } from '../types';
import { formatGMT8 } from '../utils/datetime';
import { uploadCsvToFolder } from './googleDriveService';
import { toLocationId } from './googleSheetsService';

const REPORT_FOLDER_ID: string = Constants.expoConfig?.extra?.googleReportFolderId ?? '';

function itemRow(item: Item, locationColumn: string, checkedBy: string): string[] {
  // The master sheet is the source of truth: an item is only "Checked" once it
  // carries a sheet-supplied Updated At. Scans not yet submitted stay Unchecked.
  const checked = !!item.updatedAt;
  return [
    item.barcode,
    item.name,
    item.description,
    locationColumn,
    checked ? 'Checked' : 'Unchecked',
    checked ? item.updatedAt! : '',
    checked ? (item.checkedBy || checkedBy) : '',
  ];
}

export function serializeReport(locations: Location[], unknownBarcodes: UnknownBarcode[] = [], checkedBy: string = '', allLocations: Location[] = []): string {
  const rows: string[][] = [];

  for (const loc of locations) {
    rows.push([loc.name]);
    rows.push(['Barcode', 'Item Name', 'Description', 'Current Location', 'Status', 'Updated At', 'Checked By']);
    for (const item of loc.items) {
      rows.push(itemRow(item, item.currentLocation ?? '', checkedBy));
    }

    // Items from other locations whose Current Location points here — present
    // at this location but belonging elsewhere (mirrors the inventory list).
    const misplaced: { item: Item; homeName: string }[] = [];
    for (const other of allLocations) {
      if (other.id === loc.id) continue;
      for (const item of other.items) {
        if (item.currentLocation && toLocationId(item.currentLocation) === loc.id) {
          misplaced.push({ item, homeName: other.name });
        }
      }
    }
    if (misplaced.length > 0) {
      rows.push([]);
      rows.push(['Items currently here - belong elsewhere']);
      rows.push(['Barcode', 'Item Name', 'Description', 'Belongs In', 'Status', 'Updated At', 'Checked By']);
      for (const { item, homeName } of misplaced) {
        rows.push(itemRow(item, homeName, checkedBy));
      }
    }
    rows.push([]);
  }

  if (unknownBarcodes.length > 0) {
    rows.push(['Unknown barcodes - not in master list']);
    rows.push(['Location', 'Barcode']);
    for (const unknown of unknownBarcodes) {
      const loc = locations.find(l => l.id === unknown.locationId);
      rows.push([loc?.name ?? unknown.locationId, unknown.barcode]);
    }
    rows.push([]);
  }

  rows.push(['Generated by:']);
  rows.push([checkedBy]);
  rows.push([formatGMT8()]);

  return rows.map(r => r.map(cell => `"${cell.replace(/"/g, '""')}"`).join(',')).join('\n');
}

export async function exportReport(locations: Location[], unknownBarcodes: UnknownBarcode[] = [], checkedBy: string = '', allLocations: Location[] = []): Promise<void> {
  if (!REPORT_FOLDER_ID) throw new Error('Report folder is not configured.');
  const csv = serializeReport(locations, unknownBarcodes, checkedBy, allLocations);
  const fileName = `${locations.map(l => l.name).join(', ')} - ${formatGMT8()}.csv`;
  await uploadCsvToFolder(REPORT_FOLDER_ID, fileName, csv);
}
